async function seed() {
  console.log('Seeding 10 real active Pakistan jobs...');

  // 1. Delete mock seed rows
  const mockSlugs = [
    'software-engineering-intern-systems-limited-lahore-2026',
    'junior-cloud-devops-engineer-arbisoft-remote-2026',
    'embedded-systems-intern-suparco-islamabad-2026'
  ];

  for (const s of mockSlugs) {
    await supabase.from('internships').delete().eq('slug', s);
  }

  // 2. Upsert real jobs
  for (const job of REAL_PAKISTAN_JOBS) {
    if (job.meta_description && job.meta_description.length > 150) {
      job.meta_description = job.meta_description.substring(0, 147).trim() + '...';
    }
    const { error } = await supabase
      .from('internships')
      .upsert(job, { onConflict: 'slug' });
    
    if (error) {
      console.error(`Error inserting ${job.slug}:`, error.message);
    } else {
      console.log(`✓ Inserted/Updated real job: ${job.title} at ${job.company}`);
    }
  }

  console.log('All 10 real jobs seeded successfully!');
}

seed().catch(err => {
  console.error('Fatal error during seed:', err);
  process.exit(1);
});
